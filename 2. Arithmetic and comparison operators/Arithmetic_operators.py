#Arithmetic operators
print (50 + 8)        #Add

print(500 - 75)       #subtraction

print(8 * 20)         #multiplication

print(16 / 4)         #Regular Division (/) This will show us decimal numbers 25.457

print(15 // 4)        #Floor Division (//)  This erase decimal point number only 25

print(25 % 7)         #Modulo (Remainder) that remained at the end after calculate is 4

print(9 ** 4)         #Power means multiply 9 four time. 9 * 9 * 9 * 9

#Comparision Operators
print(10 == 20)       # "Equal To" (==) 10 is not equal to 20 answer is False

print(10 != 10)       # "Not Equal To" But is is opposite if both are equal then false

print(60 > 50)        # "> Greater Than"

print(100 < 50)       # "< Less Than"

print(18 >= 18)       # Greater than or Equal to

print(14 <= 20)       # Less than or Equal to

#Operator Precedence (BODMAS) bodmas follow the rule 1st mulplication, divide later - , +
print(12 * 4 + 13)    # So its answer would be 61

print(12 * (4 + 13))       # Brackets when we apply bracket computer ignore bodmas it follow brackets

#Augmented Assignment += , -= , *= , /=
health = 100
health -= 20          #When we want to score Add, sbtract, multiply 
print(health)         #A short way to change a variable’s value without writing the variable name again